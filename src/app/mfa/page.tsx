"use client";

import { Suspense, useState } from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { ShieldCheck, KeyRound, AlertCircle, ArrowLeft } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { AuthCard } from "@/features/auth/components";
import { mfaVerificationSchema, type MfaVerificationInput } from "@/features/auth/schemas";
import { useVerifyMfa } from "@/features/auth/hooks";
import { getUserFriendlyErrorMessage } from "@/utils/error";

function MFAForm() {
  const searchParams = useSearchParams();
  const mfaTicket = searchParams.get("ticket") || "transient-ticket";

  const [useBackupCode, setUseBackupCode] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const mfaMutation = useVerifyMfa();

  const {
    register,
    handleSubmit,
    setValue,
    formState: { errors },
  } = useForm<MfaVerificationInput>({
    resolver: zodResolver(mfaVerificationSchema),
    defaultValues: {
      mfaTicket,
      code: "",
      isBackupCode: false,
    },
  });

  const toggleBackupCode = () => {
    const nextVal = !useBackupCode;
    setUseBackupCode(nextVal);
    setValue("isBackupCode", nextVal);
    setValue("code", "");
  };

  const onSubmit = async (data: MfaVerificationInput) => {
    setErrorMessage(null);
    try {
      await mfaMutation.mutateAsync(data);
    } catch (err: unknown) {
      setErrorMessage(getUserFriendlyErrorMessage(err));
    }
  };

  return (
    <AuthCard
      title="Two-Factor Authentication"
      description="Enter the security code generated by your authenticator app (Google Authenticator, 1Password, YubiKey)."
      footer={
        <Link
          href="/login"
          className="inline-flex items-center text-xs font-semibold text-muted-foreground hover:text-foreground transition-colors gap-1.5"
        >
          <ArrowLeft className="h-3.5 w-3.5" /> Back to sign in
        </Link>
      }
    >
      {errorMessage && (
        <div className="rounded-lg border border-destructive/30 bg-destructive/10 p-3 text-xs text-destructive flex items-start gap-2">
          <AlertCircle className="h-4 w-4 shrink-0 mt-0.5" />
          <span>{errorMessage}</span>
        </div>
      )}

      <form onSubmit={handleSubmit(onSubmit)} className="space-y-4">
        <div className="space-y-1.5 text-center">
          <Label htmlFor="code" className="text-xs text-muted-foreground">
            {useBackupCode ? "8-Digit Backup Recovery Key" : "6-Digit Security Code"}
          </Label>
          <Input
            id="code"
            type="text"
            inputMode={useBackupCode ? "text" : "numeric"}
            maxLength={useBackupCode ? 12 : 6}
            placeholder={useBackupCode ? "XXXX-XXXX" : "000000"}
            autoComplete="one-time-code"
            autoFocus
            disabled={mfaMutation.isPending}
            error={!!errors.code}
            className="text-center font-mono text-2xl tracking-[0.3em] h-12 uppercase"
            {...register("code")}
          />
          {errors.code && (
            <p className="text-[11px] text-destructive">{errors.code.message}</p>
          )}
        </div>

        <Button
          type="submit"
          className="w-full h-10 shadow-md gap-1.5"
          isLoading={mfaMutation.isPending}
        >
          <ShieldCheck className="h-4 w-4" />
          <span>Authenticate Session</span>
        </Button>

        <div className="text-center pt-2 border-t border-border/40">
          <button
            type="button"
            onClick={toggleBackupCode}
            className="text-xs text-muted-foreground hover:text-primary transition-colors inline-flex items-center gap-1.5"
          >
            <KeyRound className="h-3.5 w-3.5" />
            <span>{useBackupCode ? "Use Authenticator App Code" : "Lost access? Use emergency backup code"}</span>
          </button>
        </div>
      </form>
    </AuthCard>
  );
}

export default function MFAPage() {
  return (
    <div className="min-h-screen flex flex-col justify-center items-center p-4 sm:p-6 bg-gradient-to-b from-background via-muted/20 to-background">
      <Suspense fallback={<div className="text-xs text-muted-foreground">Verifying session ticket...</div>}>
        <MFAForm />
      </Suspense>
    </div>
  );
}
